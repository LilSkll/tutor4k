/** A1–B2 Spanish supplements — TR/EC/SB gaps + exerciseTypes unlock */

function sb(tokens, answer, instruction, explanation, acceptableAnswers = []) {
  return {
    type: "sentence_building",
    question: tokens.join(" / "),
    options: tokens,
    answer,
    instruction,
    explanation,
    ...(acceptableAnswers.length ? { acceptableAnswers } : {}),
  };
}

function tr(question, answer, instruction, explanation, acceptableAnswers = []) {
  return {
    type: "translation",
    question,
    answer,
    instruction,
    explanation,
    ...(acceptableAnswers.length ? { acceptableAnswers } : {}),
  };
}

function ec(question, answer, instruction, explanation, acceptableAnswers = []) {
  return {
    type: "error_correction",
    question,
    answer,
    instruction,
    explanation,
    ...(acceptableAnswers.length ? { acceptableAnswers } : {}),
  };
}

