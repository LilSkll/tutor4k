#!/usr/bin/env node
/**
 * Apply exercise-quality gates + stripExerciseIndexMarks to existing
 * curated supplement modules (without regenerating from seed sources).
 *
 * Run: npx tsx scripts/sanitize-curated-supplements.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outDir = path.join(root, "src/config/exercise-seeds");

async function rewrite(exportName, fileName) {
  const mod = await import(
    pathToFileURL(path.join(outDir, `${fileName}.ts`)).href
  );
  const data = mod[exportName];
  const { sanitizeChapterExerciseMap } = await import(
    pathToFileURL(path.join(root, "src/lib/exercise-quality.ts")).href
  );
  const { cleaned, dropped } = sanitizeChapterExerciseMap(data);
  fs.writeFileSync(
    path.join(outDir, `${fileName}.ts`),
    `/** Hand-crafted supplements — generated by scripts/build-curated-supplements.mjs */\nexport const ${exportName} = ${JSON.stringify(cleaned, null, 2)} as const;\n`,
  );
  const count = Object.values(cleaned).reduce((n, arr) => n + arr.length, 0);
  console.log(`${exportName}: kept ${count}, dropped ${dropped}`);
}

await rewrite("SPANISH_CURATED_SUPPLEMENTS", "spanish-curated-supplements");
await rewrite("ENGLISH_CURATED_SUPPLEMENTS", "english-curated-supplements");
console.log("Done.");
