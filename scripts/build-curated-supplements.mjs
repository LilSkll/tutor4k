function writeModule(exportName, fileName, data) {
  const json = JSON.stringify(data, null, 2);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, `${fileName}.ts`),
    `/** Hand-crafted supplements — generated by scripts/build-curated-supplements.mjs */\nexport const ${exportName} = ${json} as const;\n`,
  );
}

function countExercises(data) {
  return Object.values(data).reduce((sum, arr) => sum + arr.length, 0);
}

