function fmt(obj) {
  return JSON.stringify(obj, null, 2)
    .replace(/"([^"]+)":/g, "$1:")
    .replace(/"/g, '"');
}

function line(d) {
  const parts = [`type: "${d.type}"`, `question: ${JSON.stringify(d.question)}`];
  if (d.instruction) parts.push(`instruction: ${JSON.stringify(d.instruction)}`);
  if (d.options) parts.push(`options: ${JSON.stringify(d.options)}`);
  parts.push(`answer: ${JSON.stringify(d.answer)}`);
  if (d.acceptableAnswers) parts.push(`acceptableAnswers: ${JSON.stringify(d.acceptableAnswers)}`);
  parts.push(`explanation: ${JSON.stringify(d.explanation)}`);
  parts.push(`grammarTopic: ${JSON.stringify(d.grammarTopic)}`, `vocabTopic: ${JSON.stringify(d.vocabTopic)}`);
  return `    { ${parts.join(", ")} },`;
}

