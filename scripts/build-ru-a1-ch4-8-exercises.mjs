function shuffleUnique(arr) {
  const u = [...new Set(arr)];
  while (u.length < 4) u.push(u[0] + "!");
  return u.slice(0, 4);
}

function cap(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function assertChapter(name, arr) {
  const types = ["multiple_choice", "fill_blank", "translation", "error_correction", "sentence_building"];
  for (const t of types) {
    const n = arr.filter((x) => x.type === t).length;
    if (n < 20) console.warn(`${name}: only ${n} ${t}`);
  }
  const keys = arr.map((x) => x.type + "\0" + x.question);
  const dup = keys.filter((k, i) => keys.indexOf(k) !== i);
  if (dup.length) console.warn(`${name} duplicates:`, dup.slice(0, 3));
}

