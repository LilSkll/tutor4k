const ruPrompts = new Set(Object.keys(MANUAL));
for (const ch of PACK_CHAPTERS) {
  for (const ex of packs[ch]?.translation ?? []) {
    ruPrompts.add(ex.question.trim());
  }
}

const missing = [...ruPrompts].filter((q) => !MANUAL[q]);
if (missing.length > 0) {
  console.error("Missing manual translations:", missing);
  process.exit(1);
}

const out = {};
for (const q of ruPrompts) {
  const m = MANUAL[q];
  out[q] = { en: m.en, de: m.de, es: m.en };
}

const dest = path.join(root, "src/config/exercise-translation-prompts.json");
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + "\n");
